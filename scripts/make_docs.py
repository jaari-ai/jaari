def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--diff", action="store_true")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()

    created = updated = skipped = 0
    for rel, body in sorted(FILES.items()):
        if rel.startswith("docs/"):
            body = GENERATED_NOTE + body
        body = body.strip("\n") + "\n"
        path = ROOT / rel
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old == body:
            continue
        if old is not None and rel in SCAFFOLD_ONCE and not args.force:
            print(f"skip    {rel}  (scaffold-once; use --force)")
            skipped += 1
            continue
        action = "create" if old is None else "update"
        print(f"{action:7} {rel}")
        if args.diff and old is not None:
            print("".join(difflib.unified_diff(
                old.splitlines(keepends=True), body.splitlines(keepends=True),
                fromfile=f"a/{rel}", tofile=f"b/{rel}")))
        if not args.dry_run:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(body, encoding="utf-8")
        created += action == "create"
        updated += action == "update"

    mode = "would change" if args.dry_run else "changed"
    print(f"\n{mode}: {created} created, {updated} updated, {skipped} skipped")


if __name__ == "__main__":
    main()
