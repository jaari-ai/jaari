def render_adr(adr_id: str) -> str:
    title, status, decision, alternatives = ADRS[adr_id]
    num = adr_id.split("-", 1)[0]
    return f"""# ADR-{num}: {title}

- **Status:** {status}
- **Date:** {ADR_DATES.get(adr_id, TODAY)}

## Decision
{decision}

## Alternatives rejected
{alternatives}

## Consequences
_TODO: fill in as implementation reveals them._
"""


def adr_table() -> str:
    rows = ["| ADR | Title | Status |", "|---|---|---|"]
    for adr_id, (title, status, _, _) in ADRS.items():
        num = adr_id.split("-", 1)[0]
        rows.append(f"| [{num}](adr/{adr_id}.md) | {title} | {status} |")
    return "\n".join(rows)


